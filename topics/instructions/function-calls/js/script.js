"use strict";

/** 
 * Creates the Canvas for our masterpiece
*/
function setup() {
    // Create a canvas at a standard resolution
    createCanvas(640,480);
}

/**
 * Draws the writes's desktop and a blank piece of paper
 */
function draw() {
    // The pink desktop
    // Every frame(essentially as long as its up you'll see it!)(keeping this for myself)
    background(255, 100, 100);
    // The blank piece of paper(Draws a rectangle)
    rect(200, 80, 240, 320); 
    // First number is the x, Second is the y, and the 3rd and 4th are the width and height


}